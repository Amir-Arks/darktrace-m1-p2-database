BEGIN;

CREATE TABLE watchlist (
    watchlist_id       BIGINT PRIMARY KEY,
    name               VARCHAR(150) NOT NULL,
    description        TEXT,
    owner_id           VARCHAR(150) NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    current_version_id BIGINT,
    CONSTRAINT uq_watchlist_owner_name UNIQUE (owner_id, name)
);

CREATE TABLE watchlist_version (
    version_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    watchlist_id   BIGINT NOT NULL,
    version_number INTEGER NOT NULL,
    expression     TEXT NOT NULL,
    scope          TEXT NOT NULL,
    severity       VARCHAR(20) NOT NULL,
    created_by     VARCHAR(150) NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_watchlist_version_watchlist
        FOREIGN KEY (watchlist_id)
        REFERENCES watchlist (watchlist_id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_watchlist_version_number
        UNIQUE (watchlist_id, version_number),

    -- Required so current_version_id can be constrained to this same watchlist.
    CONSTRAINT uq_watchlist_version_pair
        UNIQUE (watchlist_id, version_id),

    CONSTRAINT ck_watchlist_version_number_positive
        CHECK (version_number > 0),

    CONSTRAINT ck_watchlist_version_severity
        CHECK (severity IN ('low', 'medium', 'high', 'critical'))
);

-- The composite FK guarantees that the current version belongs to this watchlist.
-- It is DEFERRABLE to support inserting the watchlist and its first version in one transaction.
ALTER TABLE watchlist
    ADD CONSTRAINT fk_watchlist_current_version
    FOREIGN KEY (watchlist_id, current_version_id)
    REFERENCES watchlist_version (watchlist_id, version_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE INDEX idx_watchlist_version_history
    ON watchlist_version (watchlist_id, version_number DESC);

COMMIT;
